//! `cargo xtask font`: turns the vendored Spleen BDF file into the glyph
//! table of `neptron-ui`. BDF is a simple text format, so the parser is
//! here and needs no crate.

use std::path::Path;

/// The BDF file, relative to the repository root.
pub const BDF: &str = "crates/neptron-ui/assets/fonts/spleen/spleen-6x12.bdf";
/// The licence file of the font, relative to the repository root.
pub const LICENSE: &str = "crates/neptron-ui/assets/fonts/spleen/LICENSE";
/// The generated table, relative to the repository root.
pub const OUT: &str = "crates/neptron-ui/src/font/spleen_6x12.rs";
/// The code points the table holds: printable ASCII and the Latin-1
/// Supplement.
pub const RANGES: [(u32, u32); 2] = [(0x20, 0x7E), (0xA0, 0xFF)];

/// The widest glyph box the table format holds: one byte per row.
const MAX_WIDTH_PX: u32 = 8;

/// An error in a BDF file.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum BdfError {
    /// A line has the wrong form.
    #[error("line {line}: {reason}")]
    Line {
        /// The line number, from 1.
        line: usize,
        /// What is wrong.
        reason: String,
    },
    /// A code point of [`RANGES`] has no glyph.
    #[error("no glyph for U+{0:04X}")]
    Missing(u32),
    /// The file has no `FONTBOUNDINGBOX` before the first glyph.
    #[error("no FONTBOUNDINGBOX before the first glyph")]
    NoBoundingBox,
    /// The glyph box is wider than one byte.
    #[error("the glyph box is {0} pixels wide; the table holds at most 8")]
    TooWide(u32),
}

/// The parsed font: the box and the glyphs of [`RANGES`], rows top first,
/// bit 7 the left column.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Font {
    width: u32,
    height: u32,
    ascent: i32,
    version: String,
    copyright: String,
    glyphs: Vec<(u32, Vec<u8>)>,
}

#[derive(Clone, Copy)]
struct BoundingBox {
    w: u32,
    h: u32,
    x: i32,
    y: i32,
}

/// Parses a BDF file and keeps the glyphs of [`RANGES`].
pub fn parse(text: &str) -> Result<Font, BdfError> {
    let mut font_box = None;
    let mut version = String::new();
    let mut copyright = String::new();
    let mut glyphs = Vec::new();
    let mut lines = text.lines().enumerate().map(|(i, l)| (i + 1, l.trim_end()));
    let mut encoding = None;
    let mut glyph_box = None;
    while let Some((n, line)) = lines.next() {
        let (key, rest) = line.split_once(' ').unwrap_or((line, ""));
        match key {
            "FONTBOUNDINGBOX" => {
                let fb = bounding_box(n, rest)?;
                // Checked here, before any glyph is placed: the table holds
                // one byte per row.
                if fb.w > MAX_WIDTH_PX {
                    return Err(BdfError::TooWide(fb.w));
                }
                font_box = Some(fb);
            }
            "FONT_VERSION" => version = rest.trim_matches('"').to_owned(),
            "COPYRIGHT" => copyright = rest.trim_matches('"').to_owned(),
            "STARTCHAR" => (encoding, glyph_box) = (None, None),
            "ENCODING" => encoding = Some(encoding_of(n, rest)?),
            "BBX" => glyph_box = Some(bounding_box(n, rest)?),
            "BITMAP" => {
                let fb = font_box.ok_or(BdfError::NoBoundingBox)?;
                let gb = glyph_box.ok_or_else(|| line_error(n, "BITMAP before BBX"))?;
                let rows: Vec<(usize, &str)> = lines.by_ref().take(gb.h as usize).collect();
                let code = encoding.ok_or_else(|| line_error(n, "BITMAP before ENCODING"))?;
                if wanted(code) {
                    // `wanted` proves that `code` is inside `RANGES`.
                    glyphs.push((code as u32, place(fb, gb, &rows)?));
                }
            }
            _ => {}
        }
    }
    let fb = font_box.ok_or(BdfError::NoBoundingBox)?;
    glyphs.sort_by_key(|(code, _)| *code);
    glyphs.dedup_by_key(|(code, _)| *code);
    for (first, last) in RANGES {
        if let Some(code) =
            (first..=last).find(|c| glyphs.binary_search_by_key(c, |g| g.0).is_err())
        {
            return Err(BdfError::Missing(code));
        }
    }
    Ok(Font {
        width: fb.w,
        height: fb.h,
        ascent: fb.h as i32 + fb.y,
        version,
        copyright,
        glyphs,
    })
}

/// The Rust source of the glyph table. `licence` is the text of the font
/// licence, copied into the header as the licence asks.
pub fn generate(font: &Font, licence: &str) -> String {
    let mut out = format!(
        "//! Generated by `cargo xtask font` from `assets/fonts/spleen/spleen-6x12.bdf`. Do not edit.\n\
         //! Spleen {}, {}x{}. {}.\n\
         //!\n\
         //! The glyphs are under the licence of the font:\n\
         //!\n",
        font.version, font.width, font.height, font.copyright
    );
    for line in licence.lines() {
        let line = line.trim_end();
        out.push_str(if line.is_empty() { "//!" } else { "//! " });
        out.push_str(line);
        out.push('\n');
    }
    out.push_str(&format!(
        "\n/// Width of the glyph box in pixels.\n\
         pub(super) const WIDTH: u32 = {};\n\
         /// Height of the glyph box in pixels.\n\
         pub(super) const HEIGHT: usize = {};\n\
         /// Rows of the glyph box above the baseline.\n\
         pub(super) const ASCENT: u32 = {};\n\
         \n\
         /// The glyphs by code point, in ascending order. Rows top first, bit 7\n\
         /// is the left column.\n\
         #[rustfmt::skip]\n\
         pub(super) static GLYPHS: [(u32, [u8; HEIGHT]); {}] = [\n",
        font.width,
        font.height,
        font.ascent,
        font.glyphs.len()
    ));
    for (code, rows) in &font.glyphs {
        let rows: Vec<String> = rows.iter().map(|r| format!("0x{r:02X}")).collect();
        out.push_str(&format!("    (0x{code:04X}, [{}]),\n", rows.join(", ")));
    }
    out.push_str("];\n");
    out
}

/// Generates the table from the files of the checkout under `root`.
pub fn generate_from(root: &Path) -> Result<String, super::UiError> {
    let bdf = read(&root.join(BDF))?;
    let licence = read(&root.join(LICENSE))?;
    let font = parse(&bdf).map_err(|source| super::UiError::Font {
        path: root.join(BDF),
        source,
    })?;
    Ok(generate(&font, &licence))
}

fn read(path: &Path) -> Result<String, super::UiError> {
    std::fs::read_to_string(path).map_err(|source| super::UiError::Io {
        path: path.to_path_buf(),
        source,
    })
}

fn wanted(code: i64) -> bool {
    RANGES
        .iter()
        .any(|&(first, last)| (i64::from(first)..=i64::from(last)).contains(&code))
}

/// The code point of an `ENCODING` line. BDF writes a glyph outside the
/// standard encoding as `ENCODING -1`, or `ENCODING -1 n` with a code `n`
/// in a private encoding; such a glyph gets `n`, or -1 when there is none.
fn encoding_of(n: usize, rest: &str) -> Result<i64, BdfError> {
    let mut fields = rest.split_whitespace();
    let code: i64 = number(n, fields.next().unwrap_or(""))?;
    match (code, fields.next()) {
        (-1, Some(private)) => number(n, private),
        _ => Ok(code),
    }
}

fn place(fb: BoundingBox, gb: BoundingBox, rows: &[(usize, &str)]) -> Result<Vec<u8>, BdfError> {
    let mut out = vec![0_u8; fb.h as usize];
    let top = (fb.h as i32 + fb.y) - (gb.h as i32 + gb.y);
    let shift = gb.x - fb.x;
    if rows.len() != gb.h as usize {
        let n = rows.last().map_or(0, |r| r.0);
        return Err(line_error(n, "the bitmap ends early"));
    }
    for (r, &(n, hex)) in rows.iter().enumerate() {
        let bits = hex.len() as u32 * 4;
        let value =
            u32::from_str_radix(hex, 16).map_err(|_| line_error(n, "a bitmap row is not hex"))?;
        for col in 0..gb.w.min(bits) {
            if value >> (bits - 1 - col) & 1 == 0 {
                continue;
            }
            let x = col as i32 + shift;
            let y = top + r as i32;
            if x < 0 || x >= fb.w as i32 || y < 0 || y >= fb.h as i32 {
                return Err(line_error(n, "a pixel is outside the font box"));
            }
            out[y as usize] |= 0x80 >> x;
        }
    }
    Ok(out)
}

fn bounding_box(n: usize, rest: &str) -> Result<BoundingBox, BdfError> {
    let v: Vec<&str> = rest.split_whitespace().collect();
    let [w, h, x, y] = v.as_slice() else {
        return Err(line_error(n, "a bounding box needs four numbers"));
    };
    Ok(BoundingBox {
        w: number(n, w)?,
        h: number(n, h)?,
        x: number(n, x)?,
        y: number(n, y)?,
    })
}

fn number<T: std::str::FromStr>(n: usize, text: &str) -> Result<T, BdfError> {
    text.parse()
        .map_err(|_| line_error(n, &format!("{text:?} is not a number")))
}

fn line_error(line: usize, reason: &str) -> BdfError {
    BdfError::Line {
        line,
        reason: reason.to_owned(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::repo::Repo;

    fn tiny_bdf(glyphs: &str) -> String {
        format!(
            "STARTFONT 2.1\nFONTBOUNDINGBOX 6 4 0 -1\nFONT_VERSION \"9\"\nCOPYRIGHT \"Me\"\nCHARS 1\n{glyphs}ENDFONT\n"
        )
    }

    fn glyph(code: u32, bbx: &str, rows: &[&str]) -> String {
        format!(
            "STARTCHAR x\nENCODING {code}\nBBX {bbx}\nBITMAP\n{}\nENDCHAR\n",
            rows.join("\n")
        )
    }

    fn all_glyphs() -> String {
        RANGES
            .iter()
            .flat_map(|&(a, b)| a..=b)
            .map(|c| glyph(c, "6 4 0 -1", &["00", "00", "00", "00"]))
            .collect()
    }

    #[test]
    fn the_committed_table_matches_the_vendored_font() {
        let root = Repo::discover().expect("repository").root;
        let generated = generate_from(&root).expect("the vendored font parses");
        let committed = std::fs::read_to_string(root.join(OUT)).expect("the table exists");
        assert!(
            generated == committed,
            "{OUT} differs from the output of `cargo xtask font`; run it and commit the result"
        );
    }

    #[test]
    fn glyphs_are_placed_in_the_font_box() {
        let small = glyph(0x41, "2 2 1 0", &["80", "40"]);
        let text = tiny_bdf(&(all_glyphs().replace("ENCODING 65\n", "ENCODING 1\n") + &small));
        let font = parse(&text).expect("valid font");
        let a = font.glyphs.iter().find(|g| g.0 == 0x41).expect("A");
        assert_eq!(a.1, [0, 0b0100_0000, 0b0010_0000, 0]);
        assert_eq!((font.width, font.height, font.ascent), (6, 4, 3));
        assert_eq!(font.glyphs.len(), 95 + 96);
    }

    #[test]
    fn unencoded_glyphs_are_accepted() {
        let solid = |encoding: &str| {
            glyph(0x41, "6 4 0 -1", &["FC", "FC", "FC", "FC"])
                .replace("ENCODING 65", &format!("ENCODING {encoding}"))
        };
        let glyphs = all_glyphs().replace("ENCODING 65\n", "ENCODING 1\n")
            + &solid("-1")
            + &solid("-1 57344")
            + &solid("-1 65");
        let font = parse(&tiny_bdf(&glyphs)).expect("valid font");
        assert_eq!(font.glyphs.len(), 95 + 96);
        let a = font.glyphs.iter().find(|g| g.0 == 0x41).expect("A");
        assert_eq!(a.1, [0xFC; 4]);
        assert!(matches!(
            encoding_of(3, "-1 x"),
            Err(BdfError::Line { line: 3, .. })
        ));
    }

    #[test]
    fn a_missing_glyph_is_an_error() {
        let text = tiny_bdf(&all_glyphs().replace("ENCODING 233\n", "ENCODING 1\n"));
        assert_eq!(parse(&text), Err(BdfError::Missing(0xE9)));
    }

    #[test]
    fn bad_files_are_rejected() {
        assert_eq!(parse("STARTFONT 2.1\n"), Err(BdfError::NoBoundingBox));
        let outside = tiny_bdf(&glyph(0x41, "2 2 5 0", &["C0", "00"]));
        assert!(matches!(
            parse(&outside),
            Err(BdfError::Line { line: 10, .. })
        ));
        let not_hex = tiny_bdf(&glyph(0x41, "6 4 0 -1", &["zz", "00", "00", "00"]));
        assert!(matches!(parse(&not_hex), Err(BdfError::Line { .. })));
        let wide = "FONTBOUNDINGBOX 9 4 0 -1\n";
        assert_eq!(parse(wide), Err(BdfError::TooWide(9)));
        let wide_glyph = "FONTBOUNDINGBOX 16 4 0 -1\nSTARTCHAR x\nENCODING 65\nBBX 16 4 0 -1\nBITMAP\nFFFF\nFFFF\nFFFF\nFFFF\nENDCHAR\n";
        assert_eq!(parse(wide_glyph), Err(BdfError::TooWide(16)));
    }

    #[test]
    fn the_output_carries_the_licence_and_the_box() {
        let font = parse(&tiny_bdf(&all_glyphs())).expect("valid font");
        let out = generate(&font, "Licence line one\nLine two");
        assert!(out.starts_with("//! Generated by `cargo xtask font`"));
        assert!(out.contains("//! Spleen 9, 6x4. Me.\n"));
        assert!(out.contains("//! Licence line one\n//! Line two\n"));
        assert!(out.contains("pub(super) const ASCENT: u32 = 3;"));
        assert!(out.contains("    (0x0041, [0x00, 0x00, 0x00, 0x00]),\n"));
        assert!(out.ends_with("];\n"));
    }
}
