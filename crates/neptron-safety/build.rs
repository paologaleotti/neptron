//! Generates the hard rails from the monitor presets in `data/monitors`.
//!
//! A preset range belongs to every class whose line rates it touches. The
//! rails of a class are the widest values among its ranges: the lowest
//! minimum and the highest maximum of each rate and line count, the
//! shortest and the longest nominal sync time, and the shortest nominal
//! porch. The line rates are clipped to the class.

#![forbid(unsafe_code)]

use std::error::Error;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

use neptron_types::{CrtRange, MonitorKind, MonitorProfile};

#[path = "src/check.rs"]
#[allow(dead_code, reason = "the build script uses only the labels")]
mod check;
#[path = "src/class.rs"]
#[allow(dead_code, reason = "the build script uses only the class list")]
mod class;

use check::Check;

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let presets = manifest.join("../../data/monitors");
    println!("cargo::rerun-if-changed={}", presets.display());
    println!("cargo::rerun-if-changed=src/check.rs");
    println!("cargo::rerun-if-changed=src/class.rs");

    let ranges = load(&presets)?;
    let mut out = String::from(
        "// Generated by build.rs from data/monitors. Do not edit.\n\
         pub(crate) const RAILS: [ClassRails; 3] = [\n",
    );
    for (name, low_mhz, high_mhz) in class::CLASSES {
        let members: Vec<&CrtRange> = ranges
            .iter()
            .filter(|r| r.h_min_mhz <= high_mhz && r.h_max_mhz >= low_mhz)
            .collect();
        if members.is_empty() {
            return Err(format!("no preset range is in the {name}").into());
        }
        write_class(&mut out, name, low_mhz, high_mhz, &members)?;
    }
    out.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR")?).join("rails.rs"), out)?;
    Ok(())
}

/// Every range of every preset, in file name order.
fn load(dir: &Path) -> Result<Vec<CrtRange>, Box<dyn Error>> {
    let mut files = Vec::new();
    for entry in fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let path = entry?.path();
        if path.extension().is_some_and(|e| e == "toml") {
            files.push(path);
        }
    }
    files.sort();
    let mut ranges = Vec::new();
    for path in files {
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let profile: MonitorProfile =
            toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        match profile.kind {
            MonitorKind::Crt { ranges: r } => ranges.extend(r),
            MonitorKind::FlatPanel { .. } | MonitorKind::Tv { .. } => {
                return Err(format!("{}: a preset must be a CRT", path.display()).into());
            }
        }
    }
    Ok(ranges)
}

fn write_class(
    out: &mut String,
    name: &str,
    low_mhz: u64,
    high_mhz: u64,
    members: &[&CrtRange],
) -> Result<(), Box<dyn Error>> {
    let min = |f: fn(&CrtRange) -> u64| members.iter().map(|r| f(r)).min().unwrap_or(0);
    let max = |f: fn(&CrtRange) -> u64| members.iter().map(|r| f(r)).max().unwrap_or(0);
    let interlaced: Vec<&&CrtRange> = members
        .iter()
        .filter(|r| r.interlaced_lines_max > 0)
        .collect();
    let interlaced_min = interlaced
        .iter()
        .map(|r| r.interlaced_lines_min)
        .min()
        .unwrap_or(0);
    let interlaced_max = interlaced
        .iter()
        .map(|r| r.interlaced_lines_max)
        .max()
        .unwrap_or(0);
    let fields: [(&str, u64); 16] = [
        ("line_rate_min_mhz", min(|r| r.h_min_mhz).max(low_mhz)),
        ("line_rate_max_mhz", max(|r| r.h_max_mhz).min(high_mhz)),
        ("field_rate_min_mhz", min(|r| r.v_min_mhz)),
        ("field_rate_max_mhz", max(|r| r.v_max_mhz)),
        (
            "progressive_lines_min",
            min(|r| u64::from(r.progressive_lines_min)),
        ),
        (
            "progressive_lines_max",
            max(|r| u64::from(r.progressive_lines_max)),
        ),
        ("interlaced_lines_min", u64::from(interlaced_min)),
        ("interlaced_lines_max", u64::from(interlaced_max)),
        ("h_sync_nominal_min_ns", min(|r| u64::from(r.h_sync_ns))),
        ("h_sync_nominal_max_ns", max(|r| u64::from(r.h_sync_ns))),
        ("v_sync_nominal_min_ns", min(|r| u64::from(r.v_sync_ns))),
        ("v_sync_nominal_max_ns", max(|r| u64::from(r.v_sync_ns))),
        (
            "h_front_porch_nominal_ns",
            min(|r| u64::from(r.h_front_porch_ns)),
        ),
        (
            "h_back_porch_nominal_ns",
            min(|r| u64::from(r.h_back_porch_ns)),
        ),
        (
            "v_front_porch_nominal_ns",
            min(|r| u64::from(r.v_front_porch_ns)),
        ),
        (
            "v_back_porch_nominal_ns",
            min(|r| u64::from(r.v_back_porch_ns)),
        ),
    ];
    writeln!(out, "    ClassRails {{")?;
    writeln!(out, "        class: {name:?},")?;
    writeln!(out, "        limits: Limits {{")?;
    for (field, value) in fields {
        writeln!(out, "            {field}: {value},")?;
    }
    writeln!(out, "        }},")?;
    writeln!(out, "        names: [")?;
    for check in Check::ALL {
        writeln!(out, "            \"{name} {}\",", check.label())?;
    }
    writeln!(out, "        ],")?;
    writeln!(out, "    }},")?;
    Ok(())
}
