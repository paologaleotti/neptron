//! Embeds the monitor presets of `data/monitors` as Rust constants.
//!
//! The binary must not depend on a TOML parser (the dependency rules allow
//! `drm`, `neptron-types` and `neptron-safety` only), so the build script
//! parses each preset with the same serde types as the rest of NEPTRON and
//! writes it out as code. A preset that does not parse fails the build.

#![forbid(unsafe_code)]

use std::error::Error;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

use neptron_types::{CrtRange, MonitorKind, MonitorProfile};

fn main() -> Result<(), Box<dyn Error>> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let dir = manifest.join("../../data/monitors");
    println!("cargo::rerun-if-changed={}", dir.display());

    let mut out = String::from(
        "// Generated by build.rs from data/monitors. Do not edit.\n\
         pub(crate) const PRESETS: &[Preset] = &[\n",
    );
    for (id, ranges) in load(&dir)? {
        writeln!(
            out,
            "    Preset {{\n        id: {id:?},\n        ranges: &["
        )?;
        for r in &ranges {
            write_range(&mut out, r)?;
        }
        writeln!(out, "        ],\n    }},")?;
    }
    out.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR")?).join("presets.rs"), out)?;
    Ok(())
}

/// Each preset as its id and its ranges.
type Presets = Vec<(String, Vec<CrtRange>)>;

/// Every preset, in file name order.
fn load(dir: &Path) -> Result<Presets, Box<dyn Error>> {
    let mut files = Vec::new();
    for entry in fs::read_dir(dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let path = entry?.path();
        if path.extension().is_some_and(|e| e == "toml") {
            files.push(path);
        }
    }
    files.sort();
    let mut presets = Vec::new();
    for path in files {
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let profile: MonitorProfile =
            toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        match profile.kind {
            MonitorKind::Crt { ranges } => presets.push((profile.id, ranges)),
            MonitorKind::FlatPanel { .. } | MonitorKind::Tv { .. } => {
                return Err(format!("{}: a preset must be a CRT", path.display()).into());
            }
        }
    }
    Ok(presets)
}

fn write_range(out: &mut String, r: &CrtRange) -> Result<(), std::fmt::Error> {
    writeln!(out, "            CrtRange {{")?;
    let fields: [(&str, String); 16] = [
        ("h_min_mhz", r.h_min_mhz.to_string()),
        ("h_max_mhz", r.h_max_mhz.to_string()),
        ("v_min_mhz", r.v_min_mhz.to_string()),
        ("v_max_mhz", r.v_max_mhz.to_string()),
        ("h_front_porch_ns", r.h_front_porch_ns.to_string()),
        ("h_sync_ns", r.h_sync_ns.to_string()),
        ("h_back_porch_ns", r.h_back_porch_ns.to_string()),
        ("v_front_porch_ns", r.v_front_porch_ns.to_string()),
        ("v_sync_ns", r.v_sync_ns.to_string()),
        ("v_back_porch_ns", r.v_back_porch_ns.to_string()),
        ("hsync_positive", r.hsync_positive.to_string()),
        ("vsync_positive", r.vsync_positive.to_string()),
        ("progressive_lines_min", r.progressive_lines_min.to_string()),
        ("progressive_lines_max", r.progressive_lines_max.to_string()),
        ("interlaced_lines_min", r.interlaced_lines_min.to_string()),
        ("interlaced_lines_max", r.interlaced_lines_max.to_string()),
    ];
    for (name, value) in fields {
        writeln!(out, "                {name}: {value},")?;
    }
    writeln!(out, "            }},")
}
